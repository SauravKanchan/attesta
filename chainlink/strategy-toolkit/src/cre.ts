// Generating a CRE workflow around a creator's strategy, then driving the
// `cre` CLI over it.
//
// `cre workflow simulate` fires a cron trigger exactly once and exits: the
// schedule string is validated but not honoured, and `--listen` is rejected for
// cron triggers. So there is no loop to start here — the platform scheduler owns
// the interval and calls simulateWorkflow() once per tick.

import { spawn } from 'node:child_process'
import { existsSync } from 'node:fs'
import { mkdir, readFile, rm, symlink, writeFile } from 'node:fs/promises'
import { homedir } from 'node:os'
import { join, relative } from 'node:path'
import ts from 'typescript'
import type { TickDecision } from '../../../shared/strategy-contract'
import type { SanityCheck } from '../../../shared/types'
import { failed, passed } from './checks'
import {
	chainlinkDir,
	CONTRACT_FILE_NAME,
	CONTRACT_SPECIFIER,
	readContractSource,
	STRATEGY_FILE_NAME,
	strategyRunnerDir,
	toolkitDir,
} from './paths'

/** Marker the generated workflow prints its decision behind. */
export const DECISION_PREFIX = 'attesta-decision:'

const DEFAULT_TARGET = 'staging-settings'
const DEFAULT_SCHEDULE = '0 */1 * * * *'
const DEFAULT_ORACLE_URL = 'http://127.0.0.1:8787/api/oracle/prices'
const DEFAULT_SECRET_NAMESPACE = 'main'
const DEFAULT_TIMEOUT_MS = 10 * 60 * 1000

export interface WorkflowOptions {
	/** Directory name for the generated workflow. Defaults to the ticker. */
	name?: string
	/** Where to generate. Defaults to <toolkit>/.workflows/<name>. */
	outDir?: string
	/** Endpoint the enclave GETs prices from, per tick. */
	oracleUrl?: string
	/** Written into config; validated by the simulator, honoured only when deployed. */
	schedule?: string
	secretNamespace?: string
	/** Maps a strategy's secret id onto the Vault id actually provisioned. */
	secretAliases?: Record<string, string>
	/** USDC under management for this tick, 6dp integer string. */
	totalAssets?: string
	currentWeightsBps?: Record<string, number>
	target?: string
	/** Path to the env file, relative to the chainlink project root. */
	envFile?: string
	timeoutMs?: number
}

export interface GeneratedWorkflow {
	/** Absolute path of the generated workflow directory. */
	dir: string
	/** Same path relative to the chainlink project root, as the CLI wants it. */
	relativeDir: string
	projectRoot: string
	name: string
	files: string[]
}

// ─── Source rewriting ───────────────────────────────────────────────────────

/**
 * Rewrites the contract's bare specifier to a relative one for the generated
 * directory. Done over the AST rather than by string replacement so a specifier
 * inside a comment or a string literal is left alone.
 */
export function rewriteContractImports(source: string, target: string): string {
	const sourceFile = ts.createSourceFile(
		STRATEGY_FILE_NAME,
		source,
		ts.ScriptTarget.ESNext,
		true,
		ts.ScriptKind.TS,
	)

	const edits: Array<{ start: number; end: number; text: string }> = []
	const visit = (node: ts.Node): void => {
		if (
			(ts.isImportDeclaration(node) || ts.isExportDeclaration(node)) &&
			node.moduleSpecifier &&
			ts.isStringLiteralLike(node.moduleSpecifier) &&
			node.moduleSpecifier.text === CONTRACT_SPECIFIER
		) {
			edits.push({
				start: node.moduleSpecifier.getStart(sourceFile),
				end: node.moduleSpecifier.getEnd(),
				text: JSON.stringify(target),
			})
		}
		ts.forEachChild(node, visit)
	}
	visit(sourceFile)

	let output = source
	for (const edit of edits.sort((a, b) => b.start - a.start)) {
		output = output.slice(0, edit.start) + edit.text + output.slice(edit.end)
	}
	return output
}

const slug = (value: string): string =>
	value
		.toLowerCase()
		.replace(/[^a-z0-9]+/g, '-')
		.replace(/^-+|-+$/g, '') || 'strategy'

