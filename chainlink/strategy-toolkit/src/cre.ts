function buildConfig(options: WorkflowOptions): string {
	return `${JSON.stringify(
		{
			schedule: options.schedule ?? DEFAULT_SCHEDULE,
			oracleUrl: options.oracleUrl ?? DEFAULT_ORACLE_URL,
			secretNamespace: options.secretNamespace ?? DEFAULT_SECRET_NAMESPACE,
			secretAliases: options.secretAliases ?? {},
			totalAssets: options.totalAssets ?? '1000000000',
			currentWeightsBps: options.currentWeightsBps ?? {},
		},
		null,
		2,
	)}\n`
}

/**
 * Writes a complete CRE workflow directory for `source`. node_modules is
 * symlinked to the reference runner's rather than installed: the dependency set
 * is pinned and identical, and a per-strategy install would put an npm fetch in
 * the middle of the submission pipeline.
 */
export async function generateWorkflow(
	source: string,
	options: WorkflowOptions = {},
): Promise<GeneratedWorkflow> {
	const projectRoot = chainlinkDir()
	const name = slug(options.name ?? 'strategy')
	const dir = options.outDir ?? join(toolkitDir(), '.workflows', name)

	await rm(dir, { recursive: true, force: true })
	await mkdir(dir, { recursive: true })

	const contractModule = `./${CONTRACT_FILE_NAME.replace(/\.ts$/, '')}`
	const runnerSrc = join(toolkitDir(), 'src', 'cre-workflow')
	const secretsPath = relative(dir, join(projectRoot, 'secrets.yaml'))
	const config = buildConfig(options)

	const files: Array<[string, string]> = [
		[STRATEGY_FILE_NAME, rewriteContractImports(source, contractModule)],
		[CONTRACT_FILE_NAME, readContractSource()],
		['workflow.ts', await readFile(join(runnerSrc, 'workflow.ts'), 'utf8')],
		['main.ts', await readFile(join(runnerSrc, 'main.ts'), 'utf8')],
		['config.staging.json', config],
		['config.production.json', config],
		['workflow.yaml', workflowYaml(`attesta-${name}`, secretsPath)],
		['package.json', workflowPackageJson(name)],
		['tsconfig.json', WORKFLOW_TSCONFIG],
	]

	await Promise.all(files.map(([file, content]) => writeFile(join(dir, file), content, 'utf8')))

	const runnerModules = join(strategyRunnerDir(), 'node_modules')
	if (existsSync(runnerModules)) {
		await symlink(relative(dir, runnerModules), join(dir, 'node_modules'), 'dir')
	}

	return {
		dir,
		relativeDir: relative(projectRoot, dir),
		projectRoot,
		name,
		files: files.map(([file]) => file),
	}
}

// ─── Driving the CLI ────────────────────────────────────────────────────────

export interface CreRunResult {
	ok: boolean
	exitCode: number | null
	command: string
	stdout: string
	stderr: string
	durationMs: number
}

export interface CreBuildResult extends CreRunResult {
	workflow: GeneratedWorkflow
	/** sha256 of the compiled WASM — the strategy's permanent identity. */
	binaryHash: string | null
	configHash: string | null
	wasmPath: string
}

export interface CreSimulateResult extends CreBuildResult {
	/** The decision the strategy returned from inside the simulated enclave. */
	decision: TickDecision | null
	/** Every `[USER LOG]` line the enclave emitted, in order. */
	enclaveLogs: string[]
}

/** Resolves the `cre` binary: CRE_BIN, then PATH, then the default install. */
export function creBinary(): string {
	const fromEnv = process.env.CRE_BIN
	if (fromEnv && existsSync(fromEnv)) return fromEnv

	const installed = join(homedir(), '.cre', 'bin', 'cre')
	if (existsSync(installed)) return installed

	// Left to PATH resolution; spawn reports ENOENT clearly if it is not there.
	return 'cre'
}

function runCre(args: string[], cwd: string, timeoutMs: number): Promise<CreRunResult> {
	const binary = creBinary()
	const command = `${binary} ${args.join(' ')}`
	const startedAt = Date.now()

	return new Promise((resolve) => {
		const child = spawn(binary, args, { cwd, env: process.env })
		let stdout = ''
		let stderr = ''
		let timedOut = false

		const timer = setTimeout(() => {
			timedOut = true
			child.kill('SIGKILL')
		}, timeoutMs)

		child.stdout.on('data', (chunk: Buffer) => {
			stdout += chunk.toString()
		})
		child.stderr.on('data', (chunk: Buffer) => {
			stderr += chunk.toString()
		})

		const finish = (exitCode: number | null): void => {
			clearTimeout(timer)
			resolve({
				ok: exitCode === 0 && !timedOut,
				exitCode,
				command,
				stdout,
				stderr: timedOut ? `${stderr}\ntimed out after ${timeoutMs}ms` : stderr,
				durationMs: Date.now() - startedAt,
			})
		}

		child.on('error', (error) => {
			clearTimeout(timer)
			resolve({
				ok: false,
				exitCode: null,
				command,
				stdout,
				stderr: `${stderr}\ncould not run ${binary}: ${error.message}`,
				durationMs: Date.now() - startedAt,
			})
		})
		child.on('close', finish)
	})
}

const HASH_PATTERNS = {
	binaryHash: /Binary hash:\s*(?:0x)?([0-9a-f]{64})/i,
	configHash: /Config hash:\s*(?:0x)?([0-9a-f]{64})/i,
} as const

const matchHash = (output: string, pattern: RegExp): string | null => pattern.exec(output)?.[1] ?? null

function cliArgs(
	verb: 'build' | 'simulate',
	workflow: GeneratedWorkflow,
	options: WorkflowOptions,
): string[] {
	return [
		'workflow',
		verb,
		workflow.relativeDir,
		'--target',
		options.target ?? DEFAULT_TARGET,
		'-e',
		options.envFile ?? '.env',
	]
}

/** `cre workflow build` over a freshly generated directory. */
export async function buildWorkflow(
	source: string,
	options: WorkflowOptions = {},
): Promise<CreBuildResult> {
	const workflow = await generateWorkflow(source, options)
	const run = await runCre(
		cliArgs('build', workflow, options),
		workflow.projectRoot,
		options.timeoutMs ?? DEFAULT_TIMEOUT_MS,
	)
	const output = `${run.stdout}\n${run.stderr}`

	return {
		...run,
		workflow,
		binaryHash: matchHash(output, HASH_PATTERNS.binaryHash),
		configHash: matchHash(output, HASH_PATTERNS.configHash),
		wasmPath: join(workflow.dir, 'binary.wasm'),
	}
}

/**
 * `cre workflow simulate` over a freshly generated directory. Fires the cron
 * trigger once, then exits — call it again for the next tick.
 */
export async function simulateWorkflow(
	source: string,
	options: WorkflowOptions = {},
): Promise<CreSimulateResult> {
	const workflow = await generateWorkflow(source, options)
	const run = await runCre(
		cliArgs('simulate', workflow, options),
		workflow.projectRoot,
		options.timeoutMs ?? DEFAULT_TIMEOUT_MS,
	)
	const output = `${run.stdout}\n${run.stderr}`
	const decision = extractDecision(output)

	return {
		...run,
		// A simulation that produces no parseable decision has not done its job,
		// however cleanly the CLI exited.
		ok: run.ok && decision !== null,
		workflow,
		binaryHash: matchHash(output, HASH_PATTERNS.binaryHash),
		configHash: matchHash(output, HASH_PATTERNS.configHash),
		wasmPath: join(workflow.dir, 'binary.wasm'),
		decision,
		enclaveLogs: extractEnclaveLogs(output),
	}
}

// ─── Output parsing ─────────────────────────────────────────────────────────

const ACTIONS = new Set(['HOLD', 'REBALANCE', 'ENTER', 'EXIT'])

function asDecision(text: string): TickDecision | null {
	let parsed: unknown
	try {
		parsed = JSON.parse(text)
	} catch {
		return null
	}
	if (typeof parsed !== 'object' || parsed === null) return null

	const candidate = parsed as Partial<TickDecision>
	if (typeof candidate.action !== 'string' || !ACTIONS.has(candidate.action)) return null
	if (typeof candidate.reason !== 'string') return null
	if (typeof candidate.targetWeightsBps !== 'object' || candidate.targetWeightsBps === null) {
		return null
	}
	return candidate as TickDecision
}

/** Reads the JSON string literal that starts at the first quote after `from`. */
function readJsonStringLiteral(output: string, from: number): string | null {
	const start = output.indexOf('"', from)
	if (start === -1) return null

	for (let index = start + 1; index < output.length; index++) {
		const char = output[index]
		if (char === '\\') {
			index++
			continue
		}
		if (char === '"') {
			try {
				return JSON.parse(output.slice(start, index + 1)) as string
			} catch {
				return null
			}
		}
		if (char === '\n') return null
	}
	return null
}

/**
 * Lifts the decision out of simulator output. The `[USER LOG]` line carries it
 * verbatim; the returned value is JSON-escaped by the CLI, so that is the
 * fallback rather than the primary.
 */
export function extractDecision(output: string): TickDecision | null {
	for (const line of output.split('\n')) {
		const index = line.indexOf(DECISION_PREFIX)
		if (index === -1) continue
		const decision = asDecision(line.slice(index + DECISION_PREFIX.length).trim())
		if (decision) return decision
	}

	const resultIndex = output.indexOf('Workflow Simulation Result:')
	if (resultIndex !== -1) {
		const literal = readJsonStringLiteral(output, resultIndex)
		if (literal !== null) {
			const index = literal.indexOf(DECISION_PREFIX)
			if (index !== -1) return asDecision(literal.slice(index + DECISION_PREFIX.length).trim())
		}
	}

	return null
}

export function extractEnclaveLogs(output: string): string[] {
	const logs: string[] = []
	for (const line of output.split('\n')) {
		const index = line.indexOf('[USER LOG]')
		if (index !== -1) logs.push(line.slice(index + '[USER LOG]'.length).trim())
	}
	return logs
}

// ─── Pipeline checks ────────────────────────────────────────────────────────

const tail = (output: string, lines = 6): string =>
	output
		.split('\n')
		.map((line) => line.trim())
		.filter((line) => line.length > 0)
		.slice(-lines)
		.join(' | ')

export function creBuildCheck(result: CreBuildResult): SanityCheck {
	if (!result.ok) {
		return failed('cre-build', tail(`${result.stdout}\n${result.stderr}`))
	}
	if (!result.binaryHash) {
		return failed('cre-build', 'build succeeded but no binary hash appeared in the output')
	}
	return passed('cre-build', `binary hash ${result.binaryHash}`)
}

export function creSimulateCheck(result: CreSimulateResult): SanityCheck {
	if (!result.decision) {
		return failed(
			'cre-simulate',
			result.exitCode === 0
				? 'simulation finished without returning a parseable decision'
				: tail(`${result.stdout}\n${result.stderr}`),
		)
	}
	const weights = Object.entries(result.decision.targetWeightsBps)
		.map(([symbol, bps]) => `${symbol} ${bps}bps`)
		.join(', ')
	return passed('cre-simulate', `${result.decision.action}${weights ? ` -> ${weights}` : ''}`)
}
